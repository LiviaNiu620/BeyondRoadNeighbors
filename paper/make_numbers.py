"""Generate the paper's numbers.tex and appendix_results.tex from the run records.

usage: python paper/make_numbers.py [RESULTS_DIR] [OUT_DIR]
       (defaults: results/ and paper/generated/)

Every number in Table 1, Table 3, Section 6 and Appendix D that is not a figure is read
here from a record file; `make numbers` regenerates the files and diffs them against
paper/expected/, the versions in the paper's LaTeX source.
"""
import json, math, os, sys
_HERE = os.path.dirname(os.path.abspath(__file__))
R = sys.argv[1] if len(sys.argv) > 1 else os.path.join(_HERE, "..", "results")
OUTDIR = sys.argv[2] if len(sys.argv) > 2 else os.path.join(_HERE, "generated")
os.makedirs(OUTDIR, exist_ok=True)
def rows(f):
    p = os.path.join(R, f)
    return [json.loads(l) for l in open(p)] if os.path.exists(p) else []
def red(r): return 1 - r["tstt"] / r["initial_tstt"]
REG = ["base", "theta032", "high"]
pend = []
T = {}
for g in REG:
    rs = rows(f"revision/t1_{g}_a.jsonl") + rows(f"revision/t1_{g}_b.jsonl") + rows(f"revision/t1_{g}_r4.jsonl")
    T[g] = {r["config"]: r for r in rs}
def cell(g, cfg, hop=False, ref="exactN"):
    t = T[g]
    if cfg not in t or ref not in t:
        pend.append((g, cfg)); return r"\pending{--}", None, None
    r = t[cfg]; ret = 100 * red(r) / red(t[ref])
    mb = (r["road_hop_charged_bits"] if hop else r["total_bits"]) / 1e6
    mbs = f"{mb:.1f}" if mb < 100 else f"{mb:.0f}"
    return f"{ret:.1f} ({mbs})", ret, mb
out = ["% Generated by tools/make_numbers.py from the run records; do not edit by hand."]
def mac(name, val): out.append(f"\\newcommand{{\\{name}}}{{{val}}}")
info = {}
for g, s in zip(REG, "ABC"):
    t = T[g]
    if "exact" in t and "exactN" in t:
        a, b = 100 * red(t["exact"]), 100 * red(t["exactN"])
        info[g] = dict(ref64=a, refN=b)
        mac("RefRed" + s, f"{b:.2f}")
    else:
        mac("RefRed" + s, r"\pending{--}"); pend.append((g, "reference"))
    for name, cfg, hop in [("EpdaTwo", "N:q8+r2+warm+res", False), ("EpdaFour", "N:q8+r4+warm+res", False),
                           ("Relay", "N:q8+r2+warm+res", True), ("TwoHop", "road2N@1e-6+warm+res", True),
                           ("Nbr", "roadN@1e-6+warm+res", False)]:
        c, ret, mb = cell(g, cfg, hop); mac(name + s, c); info.setdefault(g, {})[name] = (ret, mb)
    for name, cfg, hop in [("EpdaTwoS", "N:q8+r2+warm", False), ("EpdaFourS", "N:q8+r4+warm", False), ("RelayS", "N:q8+r2+warm", True),
                           ("TwoHopS", "road2N@1e-6+warm", True), ("NbrS", "roadN@1e-6+warm", False)]:
        c, ret, mb = cell(g, cfg, hop); info[g][name] = (ret, mb)
def rng(name, fmt="{:.0f}", sep="--"):
    v = [info[g][name][1] for g in REG if info[g].get(name, (None, None))[1] is not None]
    if len(v) < 3: return r"\pending{--}"
    return fmt.format(min(v)) + sep + fmt.format(max(v))
def rrng(name):
    v = [info[g][name][0] for g in REG if info[g].get(name, (None, None))[0] is not None]
    return r"\pending{--}" if len(v) < 3 else f"{min(v):.0f}--{max(v):.0f}"
mac("NbrMbitRange", rng("Nbr", sep=" to "))
mac("EpdaMbitRange", f"{info['base']['EpdaTwo'][1]:.0f} to {math.ceil(max(info[g]['EpdaFour'][1] for g in REG)):d}")
mac("RelayMbit", rng("Relay", "{:.1f}") if rng("Relay") != r"\pending{--}" and abs(max(info[g]["Relay"][1] for g in REG) - min(info[g]["Relay"][1] for g in REG)) > 0.05
    else (f"{info['base']['Relay'][1]:.1f}" if info["base"]["Relay"][1] else r"\pending{--}"))
mac("TwoHopRetRange", rrng("TwoHop"))
mac("TwoHopMbitRange", rng("TwoHop"))
mac("TwoHopMbitStepFive", rng("TwoHopS"))
mac("NbrMbitStepFive", rng("NbrS"))
acc = [T[g]["roadN@1e-6+warm+res"].get("accepted_steps") for g in REG if "roadN@1e-6+warm+res" in T[g]]
words = {3: "three", 4: "four", 5: "five", 6: "six", 7: "seven"}
if len(acc) == 3:
    lo, hi = min(acc), max(acc)
    mac("NbrAccepted", words.get(lo, str(lo)) if lo == hi else f"{words.get(lo, lo)} to {words.get(hi, hi)}")
    ratios = [info[g]["Nbr"][1] / info[g]["EpdaTwo"][1] for g in REG]
    mac("NbrRatio", f"{min(ratios):.1f} to {max(ratios):.1f}")
else:
    mac("NbrAccepted", r"\pending{--}"); mac("NbrRatio", r"\pending{--}")
# kappa-hop masks (Appendix D and Section 6.2): coverage and Theorem 2 interval from the omission
# probe; retention and hop-charged payload from the common-ledger runs (residual form)
om = {r["protocol"]: r for r in rows("extended/omission_khop_Anaheim.jsonl") if r["K"] == 16}
h3 = {}
for g in REG:
    rr = rows(f"revision/h3_{g}.jsonl")
    if rr and "exactN" in T[g]:
        h3[g] = (100 * red(rr[0]) / red(T[g]["exactN"]), rr[0]["road_hop_charged_bits"] / 1e6)
kh = []
for lab, prot, key in [("1", "road", "Nbr"), ("2", "road2", "TwoHop"), ("3", "road3", None)]:
    o = om[prot]; cov = o["covered"] - (16 if o["covered"] > 68 else 0)   # the probe counts the 16 own pairs for kappa >= 2
    cells = []
    for g in REG:
        v = info[g].get(key) if key else h3.get(g)
        cells.append(r"\pending{--}" if not v or v[0] is None else (f"{v[0]:.1f} ({v[1]:.1f})" if v[1] < 100 else f"{v[0]:.1f} ({v[1]:.0f})"))
    kh.append(f"{lab} & {cov}/240 & {o['err_N']:.2f} [{o['lower']:.2f}, {o['upper']:.2f}] & " + " & ".join(cells) + r"\\")
out.append("\\newcommand{\\KhopRows}{%\n" + "\n".join(kh) + "}")
def ratio_range(vals):
    lo, hi = min(vals), max(vals)
    return f"{math.floor(lo):d} to {math.ceil(hi):d}"
ep2 = {g: info[g]["EpdaTwo"][1] for g in REG}
mac("TwoHopRatio", ratio_range([info[g]["TwoHop"][1] / ep2[g] for g in REG]))
if len(h3) == 3:
    mac("ThreeHopRatio", ratio_range([h3[g][1] / ep2[g] for g in REG]))
    mac("ThreeHopRetRange", f"{min(v[0] for v in h3.values()):.0f}--{max(v[0] for v in h3.values()):.0f}")
    mac("ThreeHopMbitRange", f"{min(v[1] for v in h3.values()):.0f}--{max(v[1] for v in h3.values()):.0f}")
k32 = {r["config"]: r for r in rows("revision/h3_K32.jsonl")}
k32ref = {r["config"]: r for r in rows("revision/nb_K32.jsonl")}["exactN"]
for nm, cfg in (("KthirtytwoTwoHop", "road2N@1e-6+warm+res"), ("KthirtytwoThreeHop", "road3N@1e-6+warm+res")):
    r_ = k32[cfg]; mac(nm + "Ret", f"{100 * red(r_) / red(k32ref):.0f}"); mac(nm + "Mbit", f"{r_['road_hop_charged_bits'] / 1e6:.0f}")
_t3k32 = json.load(open(os.path.join(R, "revision/table3_residual_summary.json")))["K32"]
mac("KthirtytwoThreeHopRatio", f"{k32['road3N@1e-6+warm+res']['road_hop_charged_bits'] / 1e6 / _t3k32['mb_r']:.0f}")
# Table 3, Neighbor column on the common ledger (residual form), retention against the
# converged reference of the same run file
import statistics as _st
def nb(name):
    rs = {r["config"]: r for r in rows(f"revision/nb_{name}.jsonl")}
    if "exactN" not in rs or "roadN@1e-6+warm+res" not in rs: return None
    r = rs["roadN@1e-6+warm+res"]
    return 100 * red(r) / red(rs["exactN"]), r["total_bits"] / 1e6, 100 * red(rs["exactN"])
base_nb = (info["base"]["Nbr"][0], info["base"]["Nbr"][1], info["base"]["refN"]) if info["base"].get("Nbr", (None,))[0] is not None else None
groups = {"NbTKfour": ["K4"], "NbTKeight": ["K8"], "NbTKsixteen": [None], "NbTKthirtytwo": ["K32"], "NbTSF": ["SF8"],
          "NbTStarts": [f"seed{i}" for i in range(1, 6)], "NbTFire": [None, "fire0", "fire6", "fire11", "fire12"], "NbTRho": [None, "rho1", "rho4"]}
t3 = {}
for mname, members in groups.items():
    vals = [base_nb if x is None else nb(x) for x in members]
    if any(v is None for v in vals):
        mac(mname, r"\pending{--}"); pend.append(("table3", mname)); continue
    ret = _st.mean(v[0] for v in vals); mb = _st.mean(v[1] for v in vals)
    t3[mname] = (ret, mb, [v[0] for v in vals])
    mac(mname, f"{ret:.1f} ({mb:.1f})" if mb < 100 else f"{ret:.1f} ({mb:.0f})")
if "NbTStarts" in t3:
    mac("NbTStartsStd", f"{_st.stdev(t3['NbTStarts'][2]):.1f}")
    print("table 3 neighbor:", {k: (round(v[0], 2), round(v[1], 1)) for k, v in t3.items()})
else:
    mac("NbTStartsStd", r"\pending{--}")
# Table 3, EPDA column (residual form): Table 3 reruns, retention against the reference of the submitted record
_t3 = json.load(open(os.path.join(R, "revision/table3_residual_summary.json")))
_base_ep = {"res": info["base"]["EpdaTwo"][0], "mb_r": info["base"]["EpdaTwo"][1]}
for mname, members in {"EpTKfour": ["K4"], "EpTKeight": ["K8"], "EpTKsixteen": [None], "EpTKthirtytwo": ["K32"], "EpTSF": ["SF8"],
                       "EpTStarts": [f"seed{i}" for i in range(1, 6)], "EpTFire": [None, "fire0", "fire6", "fire11", "fire12"],
                       "EpTRho": [None, "rho1", "rho4"]}.items():
    vals = [_base_ep if x is None else _t3[x] for x in members]
    mac(mname, f"{_st.mean(v['res'] for v in vals):.1f} ({_st.mean(v['mb_r'] for v in vals):.1f})")
    if mname == "EpTStarts": mac("EpTStartsStd", f"{_st.stdev(v['res'] for v in vals):.2f}")
open(os.path.join(OUTDIR, "numbers.tex"), "w").write("\n".join(out) + "\n")

